"""Mathematical Forgery Probability Analysis.

Calculates upper bounds on eavesdropper forgery under the Quantum No-Cloning theorem
and evaluates empirical binomial consistency p-values.
"""

import math
from app.detection.models import ForgeryProbabilityAssessment


def _binomial_pmf(n: int, k: int, p: float) -> float:
    """Compute exact binomial probability mass function."""
    comb = math.comb(n, k)
    return comb * (p ** k) * ((1.0 - p) ** (n - k))


def calculate_forgery_probability(
    token_count: int,
    observed_matches: int,
    nominal_match_rate: float = 1.0,
) -> ForgeryProbabilityAssessment:
    """Evaluate mathematical forgery probability and consistency p-value."""
    if token_count <= 0:
        return ForgeryProbabilityAssessment(
            token_count=0,
            theoretical_forgery_bound=1.0,
            forgery_confidence=0.0,
            p_value=1.0,
        )

    # 1. Theoretical Upper Bound: (3/4)^L under BB84/QDS conjugate basis guessing
    # An adversary without the key who guesses conjugate bases has max 75% match probability per qubit
    theoretical_bound = round((0.75) ** token_count, 8)

    # 2. Empirical Binomial Consistency p-value
    # Null Hypothesis H0: Observed outcome is generated by legitimate state distribution with match rate p0
    p0 = max(0.01, min(0.999, nominal_match_rate))
    # Cumulative probability of getting observed_matches or fewer under H0
    p_value = 0.0
    for k in range(0, observed_matches + 1):
        p_value += _binomial_pmf(token_count, k, p0)

    p_value = min(1.0, max(0.0, p_value))

    # If all tokens match under legitimate conditions, p_value == 1.0 -> forgery_confidence == 0.0
    # If mismatches occur -> p_value approaches 0.0 -> forgery_confidence approaches 1.0
    forgery_confidence = round(1.0 - p_value, 6)

    return ForgeryProbabilityAssessment(
        token_count=token_count,
        theoretical_forgery_bound=theoretical_bound,
        forgery_confidence=forgery_confidence,
        p_value=round(p_value, 6),
    )
